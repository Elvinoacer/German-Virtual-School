"use client";

import Link from "next/link";
import { useState } from "react";
import { useQuery, useMutation, useQueryClient } from "@tanstack/react-query";
import axiosInstance from "@/lib/axios";
import { format, parseISO } from "date-fns";
import { toast } from "sonner";
import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";

interface AdminReportsData {
  kpis: {
    averageGrade: string;
    attendanceRate: number;
    revenue: number;
    activeClassrooms: number;
  };
  academicTerms: Array<{
    id: string;
    name: string;
    isCurrent: boolean;
  }>;
  recentReports: Array<{
    id: string;
    name: string;
    type: string;
    date: string;
    status: string;
    icon: string;
    color: string;
    generatedBy: string;
  }>;
}

export default function ReportsOverviewPage() {
  const [selectedTermId, setSelectedTermId] = useState<string>("current");
  const queryClient = useQueryClient();

  const { data, isLoading, isError } = useQuery<AdminReportsData>({
    queryKey: ['admin-reports', selectedTermId],
    queryFn: async () => {
      const url = selectedTermId === 'current' 
        ? '/api/admin/reports' 
        : `/api/admin/reports?termId=${selectedTermId}`;
      const response = await axiosInstance.get(url);
      return response.data.data;
    }
  });

  const generateReportMutation = useMutation({
    mutationFn: async (reportData: { name: string; type: string; format: string }) => {
      const response = await axiosInstance.post('/api/admin/reports/generate', reportData);
      return response.data;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['admin-reports'] });
      toast.success("Report generation started");
    },
    onError: () => {
      toast.error("Failed to generate report");
    }
  });

  if (isLoading) {
    return (
      <div className="flex items-center justify-center min-h-screen">
        <div className="animate-spin rounded-full h-12 w-12 border-t-2 border-b-2 border-primary"></div>
      </div>
    );
  }

  if (isError || !data) {
    return (
      <div className="flex flex-col items-center justify-center min-h-screen text-slate-900 dark:text-white">
        <span className="material-symbols-outlined text-4xl mb-2 text-red-500">error</span>
        <p>Failed to load reports data. Please try again later.</p>
        <button 
          onClick={() => queryClient.invalidateQueries({ queryKey: ['admin-reports'] })}
          className="mt-4 px-4 py-2 bg-primary text-white rounded-lg hover:bg-primary/90"
        >
          Retry
        </button>
      </div>
    );
  }

  const { kpis, recentReports, academicTerms } = data;

  const handleGenerateReport = (type: string, name: string) => {
    generateReportMutation.mutate({
      name: `${name} - ${format(new Date(), 'MMM dd')}`,
      type,
      format: 'PDF'
    });
  };

  const downloadPDF = (report: AdminReportsData['recentReports'][0]) => {
    const doc = new jsPDF();
    
    // Header
    doc.setFontSize(20);
    doc.text("German Virtual School - Report", 105, 20, { align: "center" });
    doc.setFontSize(12);
    doc.text(`Report Name: ${report.name}`, 20, 40);
    doc.text(`Type: ${report.type}`, 20, 50);
    doc.text(`Generated At: ${format(parseISO(report.date), 'PPP')}`, 20, 60);
    doc.text(`Generated By: ${report.generatedBy}`, 20, 70);

    // KPI Summary
    doc.setFontSize(16);
    doc.text("Performance Summary", 20, 90);
    
    autoTable(doc, {
      startY: 100,
      head: [['KPI', 'Value']],
      body: [
        ['Average Grade', `${kpis.averageGrade} Points`],
        ['Attendance Rate', `${kpis.attendanceRate}%`],
        ['Monthly Revenue', `KES ${kpis.revenue.toLocaleString()}`],
        ['Active Classrooms', kpis.activeClassrooms.toString()]
      ],
    });

    doc.save(`${report.name.replace(/\s+/g, '_')}.pdf`);
    toast.success("PDF Downloaded");
  };

  return (
      <div className="w-full max-w-[1440px] mx-auto px-4 sm:px-6 lg:px-8 py-6 md:py-8">
        {/* Header & Cycle Selector */}
        <div className="flex flex-col md:flex-row md:items-end justify-between gap-4 md:gap-6 mb-6 md:mb-8">
          <div className="flex flex-col gap-2 max-w-2xl">
            <h1 className="text-slate-900 dark:text-white text-3xl md:text-4xl font-black leading-tight tracking-[-0.02em]">
              Reports Overview
            </h1>
            <p className="text-slate-500 dark:text-slate-400 text-base font-normal leading-relaxed">
              View key performance indicators, attendance trends, and generate detailed 
              academic or financial reports for the selected semester.
            </p>
          </div>
          <div className="flex flex-col min-w-[240px]">
            <label
              className="text-xs font-semibold text-slate-500 dark:text-slate-400 mb-1.5 uppercase tracking-wide"
              htmlFor="cycle-select"
            >
              Select Academic Term
            </label>
            <div className="relative">
              <select
                className="w-full appearance-none bg-white dark:bg-surface-dark border border-slate-200 dark:border-slate-800 text-slate-900 dark:text-white text-sm rounded-lg focus:ring-primary focus:border-primary block p-3 pr-10 shadow-sm cursor-pointer hover:border-primary transition-colors"
                id="cycle-select"
                value={selectedTermId}
                onChange={(e) => setSelectedTermId(e.target.value)}
              >
                <option value="current">Last 30 Days (Global)</option>
                {academicTerms.map(term => (
                  <option key={term.id} value={term.id}>
                    {term.name} {term.isCurrent ? '(Active)' : ''}
                  </option>
                ))}
              </select>
              <div className="pointer-events-none absolute inset-y-0 right-0 flex items-center px-3 text-slate-500">
                <span className="material-symbols-outlined text-lg">
                  expand_more
                </span>
              </div>
            </div>
          </div>
        </div>

        {/* KPI Stats Grid */}
        <section className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-4 mb-8">
          {/* Metric 1: Academic */}
          <div className="bg-white dark:bg-surface-dark rounded-xl p-5 border border-slate-200 dark:border-slate-800 shadow-sm hover:shadow-md transition-shadow group">
            <div className="flex items-start justify-between mb-4">
              <div className="p-2 bg-blue-50 dark:bg-blue-900/20 rounded-lg text-primary">
                <span className="material-symbols-outlined">school</span>
              </div>
              <span className="inline-flex items-center gap-1 rounded-full bg-green-50 dark:bg-green-900/20 px-2 py-1 text-xs font-medium text-green-700 dark:text-green-400">
                <span className="material-symbols-outlined text-[14px]">
                  trending_up
                </span>
                Stable
              </span>
            </div>
            <p className="text-slate-500 dark:text-slate-400 text-sm font-medium mb-1">
              Average Grade
            </p>
            <div className="flex items-baseline gap-2">
              <h3 className="text-3xl font-bold text-slate-900 dark:text-white">
                {kpis.averageGrade}
              </h3>
              <span className="text-sm font-medium text-slate-500 dark:text-slate-400">
                Points
              </span>
            </div>
            {/* Micro chart (CSS) */}
            <div className="mt-4 flex items-end gap-1 h-8 opacity-60 group-hover:opacity-100 transition-opacity">
              <div className="w-full bg-primary/10 dark:bg-primary/20 rounded-t h-3/5"></div>
              <div className="w-full bg-primary/20 dark:bg-primary/30 rounded-t h-4/5"></div>
              <div className="w-full bg-primary/10 dark:bg-primary/20 rounded-t h-2/5"></div>
              <div className="w-full bg-primary/30 dark:bg-primary/40 rounded-t h-3/5"></div>
              <div className="w-full bg-primary rounded-t h-full"></div>
            </div>
          </div>
          {/* Metric 2: Attendance */}
          <div className="bg-white dark:bg-surface-dark rounded-xl p-5 border border-slate-200 dark:border-slate-800 shadow-sm hover:shadow-md transition-shadow group">
            <div className="flex items-start justify-between mb-4">
              <div className="p-2 bg-purple-50 dark:bg-purple-900/20 rounded-lg text-purple-600 dark:text-purple-400">
                <span className="material-symbols-outlined">groups</span>
              </div>
              <span className="inline-flex items-center gap-1 rounded-full bg-green-50 dark:bg-green-900/20 px-2 py-1 text-xs font-medium text-green-700 dark:text-green-400">
                <span className="material-symbols-outlined text-[14px]">
                  trending_up
                </span>
                Active
              </span>
            </div>
            <p className="text-slate-500 dark:text-slate-400 text-sm font-medium mb-1">
              Student Attendance
            </p>
            <h3 className="text-3xl font-bold text-slate-900 dark:text-white">
              {kpis.attendanceRate}%
            </h3>
            <div className="mt-4 flex items-center gap-2">
              <div className="h-1.5 w-full bg-slate-100 dark:bg-slate-700 rounded-full overflow-hidden">
                <div className="h-full bg-purple-500 rounded-full" style={{ width: `${kpis.attendanceRate}%` }}></div>
              </div>
              <span className="text-xs text-slate-500 font-medium">
                Goal 90%
              </span>
            </div>
          </div>
          {/* Metric 3: Finance */}
          <div className="bg-white dark:bg-surface-dark rounded-xl p-5 border border-slate-200 dark:border-slate-800 shadow-sm hover:shadow-md transition-shadow group">
            <div className="flex items-start justify-between mb-4">
              <div className="p-2 bg-emerald-50 dark:bg-emerald-900/20 rounded-lg text-emerald-600 dark:text-emerald-400">
                <span className="material-symbols-outlined">payments</span>
              </div>
              <span className="inline-flex items-center gap-1 rounded-full bg-slate-100 dark:bg-slate-800 px-2 py-1 text-xs font-medium text-slate-600 dark:text-slate-300">
                Month Revenue
              </span>
            </div>
            <p className="text-slate-500 dark:text-slate-400 text-sm font-medium mb-1">
              Total Revenue (Collected)
            </p>
            <h3 className="text-3xl font-bold text-slate-900 dark:text-white">
              KES {kpis.revenue.toLocaleString()}
            </h3>
            <div className="mt-4 flex items-end gap-1 h-8 opacity-60 group-hover:opacity-100 transition-opacity">
              <div className="w-full bg-emerald-100 dark:bg-emerald-900/30 rounded-t h-2/5"></div>
              <div className="w-full bg-emerald-200 dark:bg-emerald-900/50 rounded-t h-3/5"></div>
              <div className="w-full bg-emerald-500 dark:bg-emerald-600 rounded-t h-4/5"></div>
              <div className="w-full bg-emerald-300 dark:bg-emerald-700 rounded-t h-3/5"></div>
              <div className="w-full bg-emerald-600 dark:bg-emerald-500 rounded-t h-full"></div>
            </div>
          </div>
          {/* Metric 4: Active Classrooms */}
          <div className="bg-white dark:bg-surface-dark rounded-xl p-5 border border-slate-200 dark:border-slate-800 shadow-sm hover:shadow-md transition-shadow group">
            <div className="flex items-start justify-between mb-4">
              <div className="p-2 bg-orange-50 dark:bg-orange-900/20 rounded-lg text-orange-600 dark:text-orange-400">
                <span className="material-symbols-outlined">videocam</span>
              </div>
              <span className="inline-flex items-center gap-1 rounded-full bg-orange-50 dark:bg-orange-900/20 px-2 py-1 text-xs font-medium text-orange-700 dark:text-orange-400 animate-pulse">
                Live Now
              </span>
            </div>
            <p className="text-slate-500 dark:text-slate-400 text-sm font-medium mb-1">
              Active Classrooms
            </p>
            <h3 className="text-3xl font-bold text-slate-900 dark:text-white">
              {kpis.activeClassrooms}
            </h3>
            <div className="mt-4 flex gap-2 overflow-hidden">
               <span className="text-xs text-slate-500 self-center">
                 Teachers online
               </span>
            </div>
          </div>
        </section>

        {/* Main Content Area: Reports List & Quick Actions */}
        <div className="grid grid-cols-1 lg:grid-cols-3 gap-8">
          {/* Left Column: Recent Activity / Reports */}
          <div className="lg:col-span-2 flex flex-col gap-5">
            <div className="flex items-center justify-between px-1">
              <h3 className="text-slate-900 dark:text-white text-xl font-bold tracking-tight">
                Recent Reports Log
              </h3>
              <Link
                className="text-primary text-sm font-medium hover:underline flex items-center gap-1"
                href="#"
              >
                View all history
                <span className="material-symbols-outlined text-sm">
                  arrow_forward
                </span>
              </Link>
            </div>
            <div className="bg-white dark:bg-surface-dark rounded-xl border border-slate-200 dark:border-slate-800 shadow-sm overflow-hidden transition-colors duration-200">
              <div className="overflow-x-auto">
                <table className="w-full text-left text-sm whitespace-nowrap">
                  <thead className="bg-slate-50 dark:bg-slate-800 border-b border-slate-200 dark:border-slate-800">
                    <tr>
                      <th className="px-6 py-4 font-semibold text-slate-500 dark:text-slate-400">
                        Report Name
                      </th>
                      <th className="px-6 py-4 font-semibold text-slate-500 dark:text-slate-400">
                        Type
                      </th>
                      <th className="px-6 py-4 font-semibold text-slate-500 dark:text-slate-400">
                        Generated At
                      </th>
                      <th className="px-6 py-4 font-semibold text-slate-500 dark:text-slate-400">
                        Status
                      </th>
                      <th className="px-6 py-4 font-semibold text-slate-500 dark:text-slate-400 text-right">
                        Action
                      </th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-200 dark:divide-slate-800">
                    {recentReports.map((report) => (
                      <tr key={report.id} className="hover:bg-slate-50 dark:hover:bg-slate-800/50 transition-colors">
                        <td className="px-6 py-4 font-medium text-slate-900 dark:text-white flex items-center gap-3">
                          <div className={`size-8 rounded bg-${report.color}-100 dark:bg-${report.color}-900/30 flex items-center justify-center text-${report.color}-600 dark:text-${report.color}-400`}>
                            <span className="material-symbols-outlined text-lg">
                              {report.icon}
                            </span>
                          </div>
                          <div className="flex flex-col">
                            <span className="font-bold">{report.name}</span>
                            <span className="text-[10px] text-slate-400">By {report.generatedBy}</span>
                          </div>
                        </td>
                        <td className="px-6 py-4 text-slate-500 dark:text-slate-400">
                          {report.type}
                        </td>
                        <td className="px-6 py-4 text-slate-900 dark:text-white">
                          {format(parseISO(report.date), 'MMM dd, yyyy HH:mm')}
                        </td>
                        <td className="px-6 py-4">
                          <span className={`inline-flex items-center rounded-full px-2 py-1 text-xs font-medium ring-1 ring-inset ${
                            report.status === 'READY' 
                              ? 'bg-green-50 dark:bg-green-900/20 text-green-700 dark:text-green-400 ring-green-600/20'
                              : 'bg-yellow-50 dark:bg-yellow-900/20 text-yellow-700 dark:text-yellow-400 ring-yellow-600/20'
                          }`}>
                            {report.status}
                          </span>
                        </td>
                        <td className="px-6 py-4 text-right">
                          <button 
                            className={`transition-colors ${report.status === 'READY' ? 'text-slate-500 hover:text-primary' : 'text-slate-300 cursor-not-allowed'}`}
                            onClick={() => report.status === 'READY' && downloadPDF(report)}
                            disabled={report.status !== 'READY'}
                          >
                            <span className="material-symbols-outlined">
                              download
                            </span>
                          </button>
                        </td>
                      </tr>
                    ))}
                    {recentReports.length === 0 && (
                      <tr>
                        <td colSpan={5} className="px-6 py-12 text-center text-slate-500 italic">
                          No reports generated yet for this period.
                        </td>
                      </tr>
                    )}
                  </tbody>
                </table>
              </div>
            </div>
          </div>

          {/* Right Column: Quick Actions & Alerts */}
          <div className="flex flex-col gap-8">
            {/* Quick Generate */}
            <div className="flex flex-col gap-4">
              <h3 className="text-slate-900 dark:text-white text-xl font-bold tracking-tight px-1">
                Quick Actions
              </h3>
              <div className="bg-white dark:bg-surface-dark rounded-xl p-4 border border-slate-200 dark:border-slate-800 shadow-sm transition-colors duration-200">
                <div className="grid grid-cols-2 gap-3">
                  <button 
                    onClick={() => handleGenerateReport('ACADEMIC', 'Grades Report')}
                    className="flex flex-col items-center justify-center gap-2 p-4 rounded-lg bg-slate-50 dark:bg-slate-800 hover:bg-primary/5 hover:border-primary/30 border border-transparent transition-all group"
                  >
                    <span className="material-symbols-outlined text-3xl text-primary group-hover:scale-110 transition-transform">
                      school
                    </span>
                    <span className="text-xs font-medium text-slate-900 dark:text-white">
                      Academic
                    </span>
                  </button>
                  <button 
                    onClick={() => handleGenerateReport('FINANCIAL', 'Revenue Report')}
                    className="flex flex-col items-center justify-center gap-2 p-4 rounded-lg bg-slate-50 dark:bg-slate-800 hover:bg-primary/5 hover:border-primary/30 border border-transparent transition-all group"
                  >
                    <span className="material-symbols-outlined text-3xl text-slate-500 group-hover:text-primary group-hover:scale-110 transition-transform">
                      payments
                    </span>
                    <span className="text-xs font-medium text-slate-900 dark:text-white">
                      Financial
                    </span>
                  </button>
                  <button 
                    onClick={() => handleGenerateReport('ATTENDANCE', 'Attendance Log')}
                    className="flex flex-col items-center justify-center gap-2 p-4 rounded-lg bg-slate-50 dark:bg-slate-800 hover:bg-primary/5 hover:border-primary/30 border border-transparent transition-all group"
                  >
                    <span className="material-symbols-outlined text-3xl text-slate-500 group-hover:text-primary group-hover:scale-110 transition-transform">
                      groups
                    </span>
                    <span className="text-xs font-medium text-slate-900 dark:text-white">
                      Attendance
                    </span>
                  </button>
                  <button className="flex flex-col items-center justify-center gap-2 p-4 rounded-lg bg-slate-50 dark:bg-slate-800 hover:bg-primary/5 hover:border-primary/30 border border-transparent transition-all group cursor-not-allowed opacity-50">
                    <span className="material-symbols-outlined text-3xl text-slate-500 group-hover:text-primary group-hover:scale-110 transition-transform">
                      settings_suggest
                    </span>
                    <span className="text-xs font-medium text-slate-900 dark:text-white">
                      Audit Logs
                    </span>
                  </button>
                </div>
              </div>
            </div>

            {/* System Alerts */}
            <div className="flex flex-col gap-4">
              <h3 className="text-slate-900 dark:text-white text-xl font-bold tracking-tight px-1">
                System Alerts
              </h3>
              <div className="flex flex-col gap-3">
                <div className="bg-blue-50 dark:bg-blue-900/10 border-l-4 border-blue-500 p-4 rounded-r-lg">
                  <div className="flex items-start gap-3">
                    <span className="material-symbols-outlined text-blue-600 dark:text-blue-400 mt-0.5 text-lg">
                      info
                    </span>
                    <div>
                      <p className="text-sm font-semibold text-slate-900 dark:text-white">
                        Mid-Term Grades Due
                      </p>
                      <p className="text-xs text-slate-500 dark:text-slate-400 mt-1">
                        Teachers are required to submit midterm evaluations by Friday 5PM.
                      </p>
                    </div>
                  </div>
                </div>
                <div className="bg-yellow-50 dark:bg-yellow-900/10 border-l-4 border-yellow-500 p-4 rounded-r-lg">
                  <div className="flex items-start gap-3">
                    <span className="material-symbols-outlined text-yellow-600 dark:text-yellow-400 mt-0.5 text-lg">
                      warning
                    </span>
                    <div>
                      <p className="text-sm font-semibold text-slate-900 dark:text-white">
                        Scheduled Maintenance
                      </p>
                      <p className="text-xs text-slate-500 dark:text-slate-400 mt-1">
                        System update scheduled for Sunday at 02:00 AM.
                      </p>
                    </div>
                  </div>
                </div>
              </div>
            </div>
          </div>
        </div>
      </div>
  );
}
